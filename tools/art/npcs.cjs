const brows = (y, col, w = 1.8, lift = 0) => S(`M52 ${y + lift} C54.5 ${y - 1.5} 58 ${y - 1.5} 60.5 ${y - 0.5} M67.5 ${y - 0.5} C70 ${y - 1.5} 73.5 ${y - 1.5} 76 ${y + lift}`, col, w);
const nose = (y, col = C.skinD) => S(`M64 ${y} C63 ${y + 5} 63 ${y + 7} 65.5 ${y + 7.5}`, col, 1.6);
const hand = (x, y, O, skin = C.skin, skinD = C.skinD) => ell(x, y, 8, 6.5, skin, O * 0.75) + S(`M${x - 5} ${y - 2} h9 M${x - 5} ${y + 2} h9`, skinD, 1.2);

