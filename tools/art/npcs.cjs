// Village NPCs and the new monsters, drawn in the same 128x128 bust space as figures.cjs
// (bust centred at x=64; `clip` is clipped to the token disc, `over` may break it).
const { C, r1, P, F, S, L, circ, ell, rect, radial, linear, star } = require('./common.cjs');
const MIR = 'transform="matrix(-1 0 0 1 128 0)"';
const shade = (d, op = 0.22) => F(d, C.ink, `opacity="${op}"`);
const BODY = 'M8 130 C12 102 34 92 64 92 C94 92 116 102 120 130 Z';
const HEAD = 'M46 58 C46 41 54 32 64 32 C74 32 82 41 82 58 C82 73 74 84 64 84 C54 84 46 73 46 58 Z';
const HEAD_SH = 'M66 32.2 C75 34 82 43 82 58 C82 73 74 84 64 84 C70 77 73 68 72 58 C71 47 69 38 66 32.2 Z';

function head(O, skin = C.skin, skinD = C.skinD, d = HEAD, sh = HEAD_SH, earY = 62) {
  const o2 = O * 0.75;
  return ell(46.5, earY, 4, 6, skin, o2) + ell(81.5, earY, 4, 6, skin, o2) + F(`M80 ${earY - 3} q3 3 0 6`, skinD) +
    P(d, skin, O) + F(sh, skinD, 'opacity="0.45"') + S(d, C.ink, O);
}
const eyes = (y, r = 2.4, dx = 7) => circ(64 - dx, y, r, C.ink, 0) + circ(64 + dx, y, r, C.ink, 0) +
  circ(r1(64 - dx + r * 0.35), r1(y - r * 0.35), r1(r * 0.3), '#ffffff', 0, 'opacity="0.8"') + circ(r1(64 + dx + r * 0.35), r1(y - r * 0.35), r1(r * 0.3), '#ffffff', 0, 'opacity="0.8"');
